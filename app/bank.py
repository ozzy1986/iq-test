def verbal(rng: Random, difficulty: int) -> Item:
    _, prompt, options, right, explain = rng.choice([v for v in VERBAL if v[0] == difficulty])
    options = options[:]
    rng.shuffle(options)
    return prompt, options, options.index(right), explain


# ---- логические ----
NAMES = ["Аня", "Боря", "Вика", "Гоша", "Даша", "Егор", "Женя", "Зоя", "Илья", "Катя", "Лёша", "Маша"]
DAYS = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]
DAYS_ACC = ["понедельник", "вторник", "среду", "четверг", "пятницу", "субботу", "воскресенье"]


def _numeric(rng: Random, right: int, wrong: list[int], n: int = 5) -> tuple[list[str], int]:
    """Варианты-числа: верный + ближайшие правдоподобные ошибки, без повторов."""
    pool = [w for w in dict.fromkeys(wrong) if w != right and w > 0]
    extra = right + 1
    while len(pool) < n - 1:
        if extra != right and extra not in pool:
            pool.append(extra)
        extra += 1
    options = pool[: n - 1] + [right]
    rng.shuffle(options)
    return [str(o) for o in options], options.index(right)


def _order3(rng: Random) -> Item:
    a, b, c = rng.sample(NAMES, 3)
    word, top, bottom = rng.choice([("выше", "выше всех", "ниже всех"), ("старше", "старше всех", "младше всех")])
    ask_top = rng.random() < 0.5
    asked = top if ask_top else bottom
    right = a if ask_top else c
    options = [a, b, c, "Нельзя определить"]
    return (f"{a} {word}, чем {b}. {b} {word}, чем {c}. Кто из них {asked}?", options, options.index(right),
            f"По убыванию: {a}, {b}, {c}. Значит, {asked} — {right}.")


def _weekday(rng: Random) -> Item:
    start, shift = rng.randrange(7), rng.randint(8, 12)
    right = DAYS[(start + shift) % 7]
    options = rng.sample([d for d in DAYS if d != right], 4) + [right]
    rng.shuffle(options)
    return (f"Сегодня {DAYS[start]}. Какой день недели будет через {shift} дней?",
            [o.capitalize() for o in options], options.index(right),
            f"{shift} дней — это неделя и ещё {shift - 7}. Отсчитываем {shift - 7} от «{DAYS[start]}» — получаем «{right}».")


def _order4(rng: Random) -> Item:
    a, b, c, d = rng.sample(NAMES, 4)  # истинный порядок: d, a, b, c
    clues = [f"{a} бегает быстрее, чем {b}.", f"{c} бегает медленнее, чем {b}.", f"{d} бегает быстрее, чем {a}."]
    rng.shuffle(clues)
    ask_fast = rng.random() < 0.5
    options = [a, b, c, d]
    rng.shuffle(options)
    right = d if ask_fast else c
    return (" ".join(clues) + f" Кто бегает {'быстрее' if ask_fast else 'медленнее'} всех?",
            options + ["Нельзя определить"], options.index(right),
            f"От самого быстрого к самому медленному: {d}, {a}, {b}, {c}.")


def _pen(rng: Random) -> Item:
    pen = rng.choice([5, 10, 15, 20])
    diff = rng.choice([100, 200])
    total = diff + 2 * pen
    options, right = _numeric(rng, pen, [total - diff, pen * 2 + 5, diff // 10, pen + 5, pen * 3])
    return (f"Тетрадь и ручка вместе стоят {total} ₽. Тетрадь дороже ручки на {diff} ₽. Сколько рублей стоит ручка?",
            options, right,
            f"Ручка — {pen} ₽, тетрадь — {pen + diff} ₽, вместе {total} ₽. "
            f"При ручке за {total - diff} ₽ тетрадь стоила бы {total} ₽, и сумма вышла бы больше.")


def _day_shift(rng: Random) -> Item:
    before = rng.randrange(7)  # позавчера
    right = DAYS[(before + 4) % 7]
    options = rng.sample([d for d in DAYS if d != right], 4) + [right]
    rng.shuffle(options)
    return (f"Позавчерашний день — {DAYS[before]}. Какой день недели будет послезавтра?",
            [o.capitalize() for o in options], options.index(right),
            f"От позавчера до послезавтра — четыре дня. Отсчитываем четыре дня и попадаем на {DAYS_ACC[(before + 4) % 7]}.")


def _machines(rng: Random) -> Item:
    n, m = rng.choice([5, 6, 7, 8]), rng.choice([40, 60, 100])
    options, right = _numeric(rng, n, [m, 1, m // n, n * 2, m * n // 10])
    return (f"{n} станков за {n} минут делают {n} деталей. За сколько минут {m} станков сделают {m} деталей?",
            options, right,
            f"Один станок делает одну деталь за {n} минут. {m} станков за те же {n} минут сделают {m} деталей.")


