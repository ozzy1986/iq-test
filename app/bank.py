        ("Некоторые студенты — спортсмены. Все спортсмены встают рано. Что из этого следует наверняка?",
         ["Все студенты встают рано", "Некоторые студенты встают рано", "Ни один студент не встаёт рано",
          "Ничего из перечисленного"], "Некоторые студенты встают рано",
         "Те студенты, которые спортсмены, встают рано. Про остальных студентов ничего не известно."),
